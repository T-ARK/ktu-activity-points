"""Pure deterministic aggregation engine.

Computes points, runs pessimistic & optimistic passes, applies deduplication,
enforces caps in fixed sequence, and evaluates credit thresholds (G1 guarantee).
"""

from typing import Any

from app.engine.caps import apply_period_limits, apply_shared_and_category_caps, apply_subhead_caps
from app.engine.dedupe import deduplicate_events
from app.engine.scoring import calculate_raw_points
from app.schemas.facts import CertificateFacts
from app.schemas.profile import EntryType, StudentProfile
from app.schemas.result import ActivityOutcome, EngineResult, GroupResult, PointBracket
from app.schemas.verdict import Verdict


def get_requirements(profile: StudentProfile) -> tuple[int, int]:
    """Returns (total_required, per_group_required) points based on entry and PwD status."""
    if profile.is_pwd:
        return 60, 20
    if profile.entry_type == EntryType.LATERAL:
        return 90, 30
    return 120, 40


def _run_pass(
    facts_with_points: list[tuple[CertificateFacts, int]],
    rules_by_id: dict[str, Any],
    reading_mode: str = "standard",
) -> tuple[list[tuple[CertificateFacts, int]], list[str]]:
    """Runs a single evaluation pass: Dedupe -> Period Limits -> Subhead Caps -> Category Caps."""
    # Step 2: Event Deduplication (Rule i)
    deduped, dedupe_notes = deduplicate_events(facts_with_points, rules_by_id)

    # Step 3: Period Limits
    period_limited = apply_period_limits(deduped, rules_by_id)

    # Step 4: Subhead Caps
    subhead_capped = apply_subhead_caps(period_limited, rules_by_id)

    # Step 5: Shared & Category Caps
    final_items, amb_flags = apply_shared_and_category_caps(
        subhead_capped, rules_by_id, reading_mode=reading_mode
    )

    return final_items, amb_flags


def evaluate(
    profile: StudentProfile,
    certificates: list[CertificateFacts],
    ruleset: dict[str, Any],
) -> EngineResult:
    """Evaluates student certificates deterministically against the KTU 2024 ruleset."""
    # Scheme verification (S-01)
    if str(profile.scheme).strip() != "2024":
        raise ValueError(
            f"S-01: Incompatible curriculum scheme '{profile.scheme}'. Ruleset is 2024."
        )

    rules_by_id = {str(r["id"]): r for r in ruleset.get("rules", [])}
    req_total, req_group = get_requirements(profile)

    # 1. Compute raw points for all certificates
    raw_scored: list[tuple[CertificateFacts, int]] = []
    for fact in certificates:
        rule = rules_by_id.get(fact.rule_id)
        if not rule:
            raw_scored.append((fact, 0))
            continue

        # Ineligible activities always yield 0 points
        if fact.verdict in [Verdict.NOT_ELIGIBLE, Verdict.MANUAL_ONLY]:
            raw_scored.append((fact, 0))
        else:
            raw_pts = calculate_raw_points(fact, rule)
            raw_scored.append((fact, raw_pts))

    # 2. Pessimistic Pass (Confirmed points): VERIFIED only
    pessimistic_input = [
        (fact, pts if fact.verdict == Verdict.VERIFIED else 0) for fact, pts in raw_scored
    ]
    pessimistic_items, pess_flags = _run_pass(pessimistic_input, rules_by_id)

    # 3. Optimistic Pass (Upper bound points): VERIFIED + DOUBT
    optimistic_input = [(fact, pts) for fact, pts in raw_scored]
    optimistic_items, opt_flags = _run_pass(optimistic_input, rules_by_id)

    # 4. Dual-Reading Check for Ambiguities (A-04)
    alt_pessimistic, _ = _run_pass(pessimistic_input, rules_by_id, reading_mode="a04_shared")
    alt_opt, _ = _run_pass(optimistic_input, rules_by_id, reading_mode="a04_shared")

    all_ambiguities = set(pess_flags + opt_flags)
    sum_std_pess = sum(pts for _, pts in pessimistic_items)
    sum_alt_pess = sum(pts for _, pts in alt_pessimistic)
    if sum_std_pess != sum_alt_pess:
        all_ambiguities.add("A-04")
        all_ambiguities.add("S-02")

    # 5. Build activity outcomes aligned by index
    activities_out: list[ActivityOutcome] = []
    for idx, (fact, raw_pts) in enumerate(raw_scored):
        rule = rules_by_id.get(fact.rule_id, {})
        grp = rule.get("group", "I")
        p_fact, p_pts = pessimistic_items[idx]
        o_fact, o_pts = optimistic_items[idx]

        # Merge doubt codes from all passes (including D-DUP generated by deduplication)
        merged_doubts = list(
            dict.fromkeys(
                list(fact.doubt_codes) + list(p_fact.doubt_codes) + list(o_fact.doubt_codes)
            )
        )

        activities_out.append(
            ActivityOutcome(
                certificate_id=fact.certificate_id,
                rule_id=fact.rule_id,
                group=grp,
                activity_title=fact.activity_title,
                raw_points=raw_pts,
                counted_points_pessimistic=p_pts,
                counted_points_optimistic=o_pts,
                verdict=fact.verdict.value,
                doubt_codes=merged_doubts,
            )
        )

    # 6. Group Aggregations & Invariant Checks
    groups: dict[str, GroupResult] = {}
    total_confirmed = 0
    total_upper = 0

    for grp_id in ["I", "II", "III"]:
        grp_activities = [a for a in activities_out if a.group == grp_id]
        grp_conf = sum(a.counted_points_pessimistic for a in grp_activities)
        grp_upper = sum(a.counted_points_optimistic for a in grp_activities)

        if grp_conf > grp_upper:
            raise RuntimeError(
                f"S-03: Invariant violation for Group {grp_id}: Confirmed ({grp_conf}) > Upper ({grp_upper})"
            )

        grp_pending = max(0, grp_upper - grp_conf)

        total_confirmed += grp_conf
        total_upper += grp_upper

        bracket = PointBracket(confirmed=grp_conf, pending=grp_pending, upper_bound=grp_upper)
        groups[grp_id] = GroupResult(
            group_id=grp_id,
            required_points=req_group,
            bracket=bracket,
            is_credit_achieved_confirmed=(grp_conf >= req_group),
            is_credit_achievable_upper=(grp_upper >= req_group),
            activities=grp_activities,
        )

    if total_confirmed > total_upper:
        raise RuntimeError(
            f"S-03: Invariant violation for Total: Confirmed ({total_confirmed}) > Upper ({total_upper})"
        )

    overall_pending = max(0, total_upper - total_confirmed)
    total_bracket = PointBracket(
        confirmed=total_confirmed, pending=overall_pending, upper_bound=total_upper
    )

    credits_confirmed = sum(1 for g in groups.values() if g.is_credit_achieved_confirmed)
    credits_upper = sum(1 for g in groups.values() if g.is_credit_achievable_upper)

    if credits_confirmed == 3 and total_confirmed >= req_total:
        status = "ACHIEVED"
    elif credits_upper == 3 and total_upper >= req_total:
        status = "ACHIEVABLE_WITH_PENDING"
    else:
        status = "DEFICIT"

    return EngineResult(
        total_bracket=total_bracket,
        required_total=req_total,
        groups=groups,
        credit_status=status,
        credits_earned_confirmed=credits_confirmed,
        credits_earned_upper=credits_upper,
        activities=activities_out,
        ambiguity_flags=sorted(all_ambiguities),
    )
